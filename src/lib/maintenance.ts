import "server-only";
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { DATA_DIR } from "./config";
import { db, getSetting, setSetting } from "./db";
import { audit } from "./audit";

/** SQLite's online snapshot includes WAL state without stopping the panel. */
export function backupDatabase(meta = { user: "automation", ip: "local" }): string {
  const directory = path.join(DATA_DIR, "backups");
  fs.mkdirSync(directory, { recursive: true, mode: 0o700 });
  const name = `panel-${Date.now()}-${crypto.randomBytes(4).toString("hex")}.sqlite`;
  const file = path.join(directory, name);
  // Reserve private permissions before SQLite opens the destination.
  fs.closeSync(fs.openSync(file, "wx", 0o600));
  try { db().prepare("VACUUM INTO ?").run(file); }
  catch (error) { fs.unlinkSync(file); throw error; }
  setSetting("backup.last_at", String(Date.now()));
  // Only rotate snapshots generated by this function, never arbitrary files.
  const snapshots = fs.readdirSync(directory).filter((entry) => /^panel-\d+-[a-f0-9]{8}\.sqlite$/.test(entry)).sort().reverse();
  for (const old of snapshots.slice(7)) fs.unlinkSync(path.join(directory, old));
  audit({ ...meta, action: "maintenance.database_backup", target: name });
  return name;
}

export function dailyDatabaseBackup(): void {
  if (process.env.VPM_AUTO_BACKUP === "0") return;
  if (Date.now() - Number(getSetting("backup.last_at") ?? 0) >= 86_400_000) backupDatabase();
}
